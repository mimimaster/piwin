const icons: Record<string, { viewBox: string; body: string }> = {};
for (const [name, component] of Object.entries(FROM_UI_KIT)) {
  const Icon = (kit as unknown as Record<string, ComponentType>)[component];
  if (!Icon) throw new Error(`ui-kit has no ${component}`);
  const markup = renderToStaticMarkup(createElement(Icon));
  const viewBox = /viewBox="([^"]+)"/.exec(markup)?.[1] ?? '0 0 24 24';
  const body = markup.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
  icons[name] = { viewBox, body };
}
for (const [name, body] of Object.entries(HAND_DRAWN)) icons[name] = { viewBox: '0 0 24 24', body };

const sorted = Object.fromEntries(Object.entries(icons).sort(([a], [b]) => a.localeCompare(b)));
const out = `// Generated by apps/desktop/scripts/emit-artifact-kit-icons.tsx. Do not edit.
// Kit v1 icon set: trusted constant markup, stroke = currentColor.
export const ARTIFACT_KIT_V1_ICONS: Readonly<Record<string, { viewBox: string; body: string }>> = ${JSON.stringify(sorted, null, 2)};
`;
writeFileSync(new URL('../../../packages/artifact/src/kit/icons-v1.ts', import.meta.url), out);
console.log(`wrote ${Object.keys(sorted).length} icons`);
