/**
 * Regenerates packages/artifact/src/emoji-icons/emoji-icon-glyphs.generated.ts
 * from the Tabler outline set (ADR 0090). Only icons named by
 * `EMOJI_ICON_NAMES` are emitted, so the bundle carries ~300 glyphs, not 5000.
 *
 *   cd apps/desktop && pnpm exec tsx scripts/emit-emoji-icon-glyphs.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { EMOJI_ICON_NAMES } from '../../../packages/artifact/src/emoji-icons/emoji-icon-map.js';

type TablerNode = [tag: string, attrs: Record<string, string>];

// @tabler/icons is the data package behind ui-kit's @tabler/icons-react.
const uiKitRequire = createRequire(new URL('../../../packages/ui-kit/package.json', import.meta.url));
// Its exports map hides both package.json and the node JSON, so locate the
// directory as the sibling pnpm links next to @tabler/icons-react.
const tablerDir = join(dirname(uiKitRequire.resolve('@tabler/icons-react/package.json')), '..', 'icons');
const tablerManifest = join(tablerDir, 'package.json');
const nodesPath = join(tablerDir, 'tabler-nodes-outline.json');
const tablerVersion = (JSON.parse(readFileSync(tablerManifest, 'utf8')) as { version: string }).version;
const outline = JSON.parse(readFileSync(nodesPath, 'utf8')) as Record<string, TablerNode[]>;

// Tabler glyphs are flat lists of shape elements; keep them structured so the
// Markdown path builds hast nodes without parsing markup.
function compactNodes(nodes: TablerNode[]): TablerNode[] {
  return nodes.map(([tag, attrs]) => [
    tag,
    Object.fromEntries(Object.entries(attrs).filter(([name]) => name !== 'key').map(([k, v]) => [k, String(v)])),
  ]);
}

const names = [...new Set(Object.values(EMOJI_ICON_NAMES))].sort();
const missing = names.filter((name) => !outline[name]);
if (missing.length > 0) {
  throw new Error(`Unknown Tabler outline icons: ${missing.join(', ')}`);
}

const lines = names.map((name) => {
  const nodes = outline[name];
  if (!nodes) throw new Error(`Unknown Tabler outline icon: ${name}`);
  return `  ${JSON.stringify(name)}: ${JSON.stringify(compactNodes(nodes))},`;
});

const output = `// Generated by apps/desktop/scripts/emit-emoji-icon-glyphs.ts. Do not edit.
// Tabler Icons ${tablerVersion} (MIT), outline, 24×24, stroke = currentColor.
import type { EmojiIconGlyphNode } from './emoji-icon-types.js';

export const EMOJI_ICON_GLYPHS: Readonly<Record<string, readonly EmojiIconGlyphNode[]>> = {
${lines.join('\n')}
};
`;

const target = new URL(
  '../../../packages/artifact/src/emoji-icons/emoji-icon-glyphs.generated.ts',
  import.meta.url,
);
writeFileSync(target, output);
console.log(`wrote ${names.length} glyphs → ${target.pathname}`);
